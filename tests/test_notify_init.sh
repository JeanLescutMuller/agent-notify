#!/bin/bash
# End-to-end scenario for `notify init`'s managed tmux-hooks block
# (tests/AGENTS.md scenario 11): fresh deploy, idempotent redeploy, content
# change producing exactly one backup, and a hand-edited block being refused
# rather than clobbered - plus the CLAUDE-NOTIFY -> AGENT-NOTIFY label
# migration. Never touches the real ~/.tmux.conf: everything runs under a
# throwaway $HOME, and the "content changed" step runs against a scratch
# copy of release/ so the real tmux-hooks.conf is never edited.
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/test_helpers.sh"
TEST_ROOT="$(mktemp -d /tmp/notify-tests.XXXXXX)"
trap 'rm -rf "$TEST_ROOT"' EXIT

HOME_DIR="$TEST_ROOT/home"
BIN="$TEST_ROOT/bin"
TMUX_CONF="$HOME_DIR/.tmux.conf"
mkdir -p "$HOME_DIR" "$BIN"

# `notify init` only needs `command -v tmux` to succeed and `tmux
# source-file` to not blow up - it doesn't need a working tmux server.
printf '%s\n' '#!/bin/bash' 'exit 0' > "$BIN/tmux"
chmod +x "$BIN/tmux"

release_copy="$TEST_ROOT/release"
cp -R "$PROJECT_DIR/release" "$release_copy"
chmod +x "$release_copy/notify"
NOTIFY_COPY="$release_copy/notify"

run_init() {
  HOME="$HOME_DIR" PATH="$BIN:$PATH" NOTIFY_RUNTIME_DIR="$TEST_ROOT/runtime" \
    NOTIFY_ROOT_DATA_DIR="$TEST_ROOT/state" \
    bash "$NOTIFY_COPY" init
}

# --- CLAUDE-NOTIFY -> AGENT-NOTIFY label migration -------------------------
# Seed a pre-existing block under the OLD label, with content that already
# matches what would be deployed today, so migration is the ONLY thing that
# should happen (no rewrite, no backup).
hooks_content="$(cat "$PROJECT_DIR/release/tmux/tmux-hooks.conf")"
hash="$(printf '%s\n' "$hooks_content" | shasum -a 256 | awk '{print $1}')"
{
  echo "# ┌─ CLAUDE-NOTIFY BLOCK ─────────────────────────────────────────────"
  echo "# │ DO NOT EDIT - auto-generated by notify. Edits inside this"
  echo "# │ block are overwritten on every install. Put your own"
  echo "# │ customizations below this block instead."
  printf '%s\n' "$hooks_content"
  echo "# │ CLAUDE-NOTIFY BLOCK END — sha256:${hash}"
  echo "# └────────────────────────────────────────────────────────────"
} > "$TMUX_CONF"

run_init >/dev/null 2>&1
grep -qF '# ┌─ AGENT-NOTIFY BLOCK' "$TMUX_CONF" || fail "init migrates the CLAUDE-NOTIFY label to AGENT-NOTIFY"
grep -qF 'CLAUDE-NOTIFY' "$TMUX_CONF" && fail "the old label must not remain anywhere in the file"
[ "$(ls "$HOME_DIR"/.tmux.conf.bak.* 2>/dev/null | wc -l | tr -d ' ')" = "0" ] || \
  fail "a pure label migration with matching content must not create a backup"
pass "notify init: migrates the CLAUDE-NOTIFY label to AGENT-NOTIFY with no rewrite"

backup_count() { ls "$HOME_DIR"/.tmux.conf.bak.* 2>/dev/null | wc -l | tr -d ' ' || true; }

# --- fresh deploy on a file with no block at all ---------------------------
# deploy_managed_block backs up the target whenever it already EXISTS,
# regardless of whether it already contains a block - so deploying onto a
# pre-existing but block-less file does create one backup (of the pre-block
# content); only deploying onto a file that doesn't exist yet skips it.
rm -f "$TMUX_CONF"
echo "# a user's own unrelated tmux config" > "$TMUX_CONF"
before_backups=$(backup_count)
run_init >/dev/null 2>&1
grep -qF '# ┌─ AGENT-NOTIFY BLOCK' "$TMUX_CONF" || fail "init deploys the block on first run"
grep -qF "$(printf '%s' "$hooks_content" | head -1)" "$TMUX_CONF" || fail "the deployed block contains the real hooks content"
grep -qF "a user's own unrelated tmux config" "$TMUX_CONF" || fail "content outside the block is preserved"
[ "$(backup_count)" = "$((before_backups + 1))" ] || \
  fail "deploying the first block onto an existing file backs up that pre-block content once"
before_deploy="$(cat "$TMUX_CONF")"
pass "notify init: fresh deploy onto an unrelated existing file"

# --- idempotent redeploy: byte-identical, no new backup --------------------
before_backups=$(backup_count)
run_init >/dev/null 2>&1
after_redeploy="$(cat "$TMUX_CONF")"
[ "$before_deploy" = "$after_redeploy" ] || fail "a redeploy with unchanged content must be a byte-identical no-op"
[ "$(backup_count)" = "$before_backups" ] || fail "an unchanged redeploy must not create a new backup"
pass "notify init: redeploying identical content is a true no-op"

# --- content change: exactly one new backup, block replaced ----------------
# Backup filenames are only second-granularity (.bak.<YYYYMMDD_HHMMSS>) - a
# `sleep 1` guarantees this backup lands in a distinct second from the one
# the previous step created, rather than silently overwriting it.
sleep 1
before_backups=$(backup_count)
printf '\n# a deliberately added test hook line\n' >> "$release_copy/tmux/tmux-hooks.conf"
run_init >/dev/null 2>&1
[ "$(backup_count)" = "$((before_backups + 1))" ] || \
  fail "a real content change creates exactly one new backup (had $before_backups, now $(backup_count))"
grep -qF 'a deliberately added test hook line' "$TMUX_CONF" || fail "the new content is actually deployed"
pass "notify init: a real content change replaces the block and backs up exactly once"

# --- hand-edited block is refused, not clobbered ---------------------------
sed -i.orig 's/user-focus"$/user-focus-HAND-EDITED"/' "$TMUX_CONF"
rm -f "$TMUX_CONF.orig"
hand_edited_content="$(cat "$TMUX_CONF")"
init_stderr="$TEST_ROOT/init.stderr"
run_init >/dev/null 2>"$init_stderr" || true
[ "$(cat "$TMUX_CONF")" = "$hand_edited_content" ] || fail "a hand-edited block must be left completely untouched"
grep -qF 'was hand-edited since it' "$init_stderr" || fail "init warns on stderr instead of silently overwriting"
pass "notify init: a hand-edited block is refused with a diff, never silently overwritten"

printf '\nAll %s notify-init scenarios passed.\n' "$pass_count"
